#.add()-ამატებს ელემენტს სიის ბოლოს
#.remove()-აშორებს ელემენტს სიიდან
#.keys()-იღებს მხოლოდ გასაღებებს
#.values()-ირებს მხოლოდ მნიშვნელობებს
#.clean()-შლის სიას
#.get()-გვაძლევს ელემენტებს
#.items()-გვინრუნებს გასაღებებს და ელემენტებს წყვილებად