#list-არის დალაგებული სია და ერთი და იგინე ელემენტების რამდენიმეჯერ გამეორება შეიძლება
#set-არის დაულაგებელი სია და იწერება {} ფრჩხილებით და ერთი და იგივე ელემენტის გამეორება არ შეიძლება


num = {1,2,3,4,5,6,7}
