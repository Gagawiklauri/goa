# 1. პირობითი ოპერატორები (if / elif / else)
# გამოიყენება გადაწყვეტილების მისაღებად
# პროგრამა ამოწმებს პირობას და ირჩევს რომელი კოდი შესრულდეს


age = 18

if age < 18:
    
    print("არასრულწლოვანი")
elif age == 18:
    
    print("ზუსტად 18 წლის")
else:
   
    print("ზრდასრული")


# 2. ციკლები (for / while)
# გამოიყენება როცა გვინდა ერთი და იგივე მოქმედება ბევრჯერ გავიმეოროთ

# for - როცა ვიცით რამდენჯერ უნდა განმეორდეს
# while - როცა პირობა მართალია, მანამდე გრძელდება


# 3. გამოტოვება და შეწყვეტა (break / continue)
# break -> აჩერებს ციკლს მთლიანად
# continue -> გამოტოვებს ერთ ნაბიჯს და გადადის შემდეგზე

for i in range(5):
    if i == 2:
        continue  # 2-ს გამოტოვებს
    if i == 4:
        break     # აქ ციკლი სრულად ჩერდება
    print(i)


# ==============================
# 1) როგორ მუშაობს For ციკლი
# ==============================

# for ციკლი გადის ელემენტებზე ან რიცხვების დიაპაზონზე (range)
# და ყოველ iteration-ზე ცვლადი იღებს ახალ მნიშვნელობას

# მაგალითი:
for i in range(3):
    # i იღებს მნიშვნელობებს: 0, 1, 2
    print(i)

# ახსნა:
# 1-ე წრე -> i = 0
# 2-ე წრე -> i = 1
# 3-ე წრე -> i = 2


# ==============================
# 2) 1-დან 1000-მდე რიცხვების გამოტანა
