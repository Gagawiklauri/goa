for i in range(1, 1001):
    print(i)  # ბეჭდავს 1-დან 1000-მდე ყველა რიცხვს


# ==============================
# 3) საყვარელი საჭმლის 15-ჯერ გამოტანა
# ==============================

favorite_food = "პიცა"  # შეცვალე შენი საყვარელი საჭმლით

for i in range(15):
    print(favorite_food)


# ==============================
# 4) ოჯახის წევრების სახელების 5-5-ჯერ გამოტანა
# ==============================

family_members = ["დედა", "მამა", "ძმა", "და"]  # შეცვალე შენი ოჯახის წევრებით

for name in family_members:
    # თითოეული სახელი იბეჭდება 5-ჯერ
    for i in range(5):
        print(name)


