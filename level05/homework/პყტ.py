#and-ორივე პირობა უნდა შესრულდეს
#not-მაგ(not false)ეს ნიშნავს რომ ტრუა
#or-ან ერთი უნდა შესრულდე ან ორივე


print(10 > 5)      # True
print(7 == 7)      # True
print(3 <= 9)      # True


print(4 > 8)       # False
print(6 == 2)      # False
print(5 < 1)       # False

print(True and True)      # True
print(True or False)      # True
print(not False)          # True


print(True and False)     # False
print(False or False)     # False
print(not True)           # False

